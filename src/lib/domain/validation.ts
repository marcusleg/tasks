/** Thrown when user input (a List name, a Task Title, …) is missing, malformed or too long. */
export class InvalidInputError extends Error {
	constructor(message: string) {
		super(message);
		this.name = 'InvalidInputError';
	}
}

/** A trimmed, non-empty string of at most `max` characters. */
export function requiredText(value: unknown, what: string, max: number): string {
	if (typeof value !== 'string') throw new InvalidInputError(`${what} must be text`);
	const trimmed = value.trim();
	if (!trimmed) throw new InvalidInputError(`${what} is required`);
	if (trimmed.length > max) {
		throw new InvalidInputError(`${what} must be at most ${max} characters`);
	}
	return trimmed;
}

/** Free text of at most `max` characters, kept as typed except for trailing whitespace. */
export function freeText(value: unknown, what: string, max: number): string {
	if (typeof value !== 'string') throw new InvalidInputError(`${what} must be text`);
	const text = value.trimEnd();
	if (text.length > max) throw new InvalidInputError(`${what} must be at most ${max} characters`);
	return text;
}

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

/** A lowercase UUID, as generated by {@link newId}. */
export function isId(value: unknown): value is string {
	return typeof value === 'string' && UUID.test(value);
}

/**
 * A random UUID v4. Clients generate the ids of the things they create, so an optimistic UI can
 * refer to a new Task before the server has answered. `crypto.randomUUID` only exists in secure
 * contexts, so plain-http deployments fall back to `getRandomValues`.
 */
export function newId(): string {
	if (typeof crypto.randomUUID === 'function') return crypto.randomUUID();
	const bytes = crypto.getRandomValues(new Uint8Array(16));
	bytes[6] = (bytes[6] & 0x0f) | 0x40;
	bytes[8] = (bytes[8] & 0x3f) | 0x80;
	const hex = [...bytes].map((byte) => byte.toString(16).padStart(2, '0')).join('');
	return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

/** The current time as an ISO string, the format of timestamps in serialized Lists and Tasks. */
export function timestamp(): string {
	return new Date().toISOString();
}
